import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ExcelJS from 'exceljs';
import { tableWorkbook } from './server/services/table-export.js';
const columns = [{key:'name',label:'Nom'},{key:'phone',label:'Téléphone'},{key:'count',label:'Leads'}];
const rows = [{id:'1',name:'École "Nidal"; محمد',phone:'+212612345678',count:12},{id:'2',name:'=SUM(A1)',phone:'0612345678',count:3}];
const buffer = await tableWorkbook({title:'Contacts',columns,rows});
const workbook = new ExcelJS.Workbook(); await workbook.xlsx.load(buffer);
const sheet = workbook.getWorksheet('Données');
assert.equal(sheet.getCell('A2').value, rows[0].name);
assert.equal(sheet.getCell('B2').value, '+212612345678');
assert.equal(sheet.getCell('B3').value, '0612345678');
assert.equal(sheet.getCell('C2').value, 12);
assert.equal(sheet.getCell('A3').type, ExcelJS.ValueType.String);
assert.ok(sheet.autoFilter);
assert.equal(sheet.views[0].ySplit, 1);
await assert.rejects(tableWorkbook({columns:[],rows}), /invalides/);
const elements = new Map();
const element = id => { if (!elements.has(id)) elements.set(id,{innerHTML:'',value:'',querySelectorAll:() => []}); return elements.get(id); };
const context = vm.createContext({console,Set,Intl,escapeHtml:String,document:{getElementById:element},NidalAPI:{},showToast:()=>{}});
vm.runInContext(fs.readFileSync('js/data-grid.js','utf8'),context);
context.columns = columns; context.rows = rows;
const csv = vm.runInContext("NidalDataGrid.delimited(columns,rows,';')",context);
assert.ok(csv.includes("'+212612345678")); assert.ok(csv.includes("'=SUM(A1)")); assert.ok(csv.includes('محمد'));
vm.runInContext("var grid = NidalDataGrid.create({id:'test',title:'Contacts',columns}); grid.setRows(rows);",context);
element('test-search').oninput({target:{value:'École'}});
assert.equal(vm.runInContext('grid.filtered().length',context),1);
element('test-select').onclick();
assert.equal(vm.runInContext("grid.scopeRows('selected')[0].id",context),'1');
element('test-search').oninput({target:{value:'SUM'}});
assert.equal(vm.runInContext("grid.scopeRows('selected').length",context),0);
assert.equal(vm.runInContext("grid.scopeRows('all').length",context),2);
element('test-search').oninput({target:{value:''}});
element('test-clear').onclick();
assert.equal(vm.runInContext("grid.scopeRows('selected').length",context),0);
context.getActiveBrand = () => 'nidal';
context.getActiveBrandLabel = () => 'Nidal';
context.location = {hash:'#leads'};
context.NidalStore = {syncRemote:async () => {}};
context.NidalAPI = {isOnline:() => true, request:async path => path.startsWith('/api/leads?') ? [{id:'lead-test',workflow_status:'RDV',created_time:'2026-10-04T09:00:00Z',form_name:'Visite',campaign_name:'Inscriptions',field_data:[{name:'full_name',values:['Parent Nidal']},{name:'phone_number',values:['0612345678']},{name:'email',values:['parent@example.com']},{name:'niveau',values:['Maternelle']}]}] : {automatic:true,intervalMinutes:15}};
vm.runInContext(fs.readFileSync('js/leads.js','utf8'),context);
vm.runInContext('LeadsView.render()',context);
await new Promise(resolve => setImmediate(resolve));
const leadHtml = element('leads-table-results').innerHTML;
assert.ok(leadHtml.includes('class="lead-name"'));
assert.ok(leadHtml.includes('href="tel:0612345678"'));
assert.ok(leadHtml.includes('mailto:parent%40example.com'));
assert.ok(leadHtml.includes('value="RDV" selected'));
assert.ok(leadHtml.includes('<details class="lead-details"'));
assert.ok(leadHtml.includes('Maternelle'));
assert.ok(!leadHtml.split('</thead>')[0].includes('Réponse : niveau'));
console.log('Exports : vrai XLSX, Unicode, téléphones, filtres, sélection et CSV validés.');
